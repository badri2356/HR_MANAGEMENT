-- =========================================================
-- NexusHR auth-service: initial schema
-- Tables: users, roles, permission, user_roles, role_permission,
--         refresh_tokens, password_reset_token, audit_log
-- =========================================================

-- ---------- users  (User extends BaseEntity) ----------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(255),
    status          VARCHAR(20),
    employee_id     BIGINT,
    failed_attempts INTEGER      DEFAULT 0,
    last_login_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ,
    created_by      VARCHAR(255),
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_email       UNIQUE (email),
    CONSTRAINT uk_users_employee_id UNIQUE (employee_id),
    CONSTRAINT ck_users_status      CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED'))
);

-- ---------- roles  (Role extends BaseEntity, @Table(name = "roles")) ----------
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(30)  NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(255),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_roles_name UNIQUE (name)
);

-- ---------- permission  (Permission extends BaseEntity, no @Table → "permission") ----------
CREATE TABLE permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(60),
    description VARCHAR(255),
    created_at  TIMESTAMPTZ,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(255),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_permission_code UNIQUE (code)
);

-- ---------- user_roles  (User.roles @ManyToMany) ----------
CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

-- ---------- role_permission  (Role.permissions @ManyToMany) ----------
CREATE TABLE role_permission (
    role_id       BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permission (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

-- ---------- refresh_tokens  (RefreshToken extends BaseEntity) ----------
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(100) NOT NULL,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ  NOT NULL,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    created_by VARCHAR(255),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_refresh_tokens_token UNIQUE (token)
);
CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);

-- ---------- password_reset_token  (PasswordResetToken extends BaseEntity) ----------
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(100) NOT NULL,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ  NOT NULL,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    created_by VARCHAR(255),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_password_reset_token_token UNIQUE (token)
);
CREATE INDEX ix_password_reset_token_user_id ON password_reset_token (user_id);

-- ---------- audit_log  (standalone, does not extend BaseEntity) ----------
CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action       VARCHAR(50),
    performed_by VARCHAR(255) NOT NULL,
    ip_address   VARCHAR(255),
    created_at   TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_audit_log_created_at ON audit_log (created_at);