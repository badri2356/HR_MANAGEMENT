CREATE TABLE salary_structures (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT        NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    basic         NUMERIC(12,2) NOT NULL,
    hra           NUMERIC(12,2) NOT NULL DEFAULT 0,
    allowances    NUMERIC(12,2) NOT NULL DEFAULT 0,
    pf_applicable BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ,
    created_by    VARCHAR(255),
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_salary_structures_employee UNIQUE (employee_id),
    CONSTRAINT ck_salary_positive CHECK (basic > 0 AND hra >= 0 AND allowances >= 0)
);

CREATE TABLE payroll_runs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year             INTEGER       NOT NULL,
    month            INTEGER       NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    working_days     INTEGER       NOT NULL,
    employee_count   INTEGER       NOT NULL DEFAULT 0,
    total_gross      NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_deductions NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_net        NUMERIC(14,2) NOT NULL DEFAULT 0,
    processed_by     VARCHAR(255),
    paid_by          VARCHAR(255),
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ,
    created_by       VARCHAR(255),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_payroll_runs_month UNIQUE (year, month),
    CONSTRAINT ck_payroll_month  CHECK (month BETWEEN 1 AND 12),
    CONSTRAINT ck_payroll_status CHECK (status IN ('DRAFT', 'PROCESSED', 'PAID'))
);

CREATE TABLE payslips (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id   BIGINT        NOT NULL REFERENCES payroll_runs (id) ON DELETE CASCADE,
    employee_id      BIGINT        NOT NULL REFERENCES employees (id),
    working_days     INTEGER       NOT NULL,
    absent_days      INTEGER       NOT NULL,
    basic            NUMERIC(12,2) NOT NULL,
    hra              NUMERIC(12,2) NOT NULL,
    allowances       NUMERIC(12,2) NOT NULL,
    gross_earnings   NUMERIC(12,2) NOT NULL,
    loss_of_pay      NUMERIC(12,2) NOT NULL,
    gross_pay        NUMERIC(12,2) NOT NULL,
    pf               NUMERIC(12,2) NOT NULL,
    professional_tax NUMERIC(12,2) NOT NULL,
    tds              NUMERIC(12,2) NOT NULL,
    total_deductions NUMERIC(12,2) NOT NULL,
    net_pay          NUMERIC(12,2) NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ,
    created_by       VARCHAR(255),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_payslips_run_employee UNIQUE (payroll_run_id, employee_id)
);

CREATE INDEX ix_payslips_employee ON payslips (employee_id);