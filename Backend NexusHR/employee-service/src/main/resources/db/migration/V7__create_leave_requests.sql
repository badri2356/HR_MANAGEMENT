CREATE TABLE leave_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT       NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    leave_type  VARCHAR(20)  NOT NULL,
    from_date   DATE         NOT NULL,
    to_date     DATE         NOT NULL,
    days        INTEGER      NOT NULL,
    reason      VARCHAR(500),
    status      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    decided_by  VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(255),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_leave_type   CHECK (leave_type IN ('CASUAL', 'SICK', 'EARNED')),
    CONSTRAINT ck_leave_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_leave_dates  CHECK (to_date >= from_date)
);

CREATE INDEX ix_leave_requests_employee ON leave_requests (employee_id);
CREATE INDEX ix_leave_requests_status ON leave_requests (status);