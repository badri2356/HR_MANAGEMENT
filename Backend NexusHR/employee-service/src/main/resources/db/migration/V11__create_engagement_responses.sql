CREATE TABLE engagement_responses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id       BIGINT        NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    month             VARCHAR(7)    NOT NULL,
    job_satisfaction  INTEGER       NOT NULL,
    manager_support   INTEGER       NOT NULL,
    work_life_balance INTEGER       NOT NULL,
    career_growth     INTEGER       NOT NULL,
    comment           VARCHAR(1000),
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ,
    created_by        VARCHAR(255),
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_engagement_once   UNIQUE (employee_id, month),        -- one response per month
    CONSTRAINT ck_engagement_rating CHECK (
        job_satisfaction  BETWEEN 1 AND 5 AND manager_support BETWEEN 1 AND 5 AND
        work_life_balance BETWEEN 1 AND 5 AND career_growth   BETWEEN 1 AND 5)
);

CREATE INDEX ix_engagement_month ON engagement_responses (month);