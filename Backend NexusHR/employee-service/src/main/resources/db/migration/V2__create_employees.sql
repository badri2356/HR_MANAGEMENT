CREATE TABLE employees (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id         BIGINT,
    employee_code   VARCHAR(20) NOT NULL,
    first_name      VARCHAR(100) NOT NULL,
    last_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    phone           VARCHAR(20),
    designation     VARCHAR(100),

    employment_type VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'ONBOARDING',

    joining_date    DATE NOT NULL,
    exit_date       DATE,
    exit_reason     VARCHAR(255),

    department_id   BIGINT,
    manager_id      BIGINT,

    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ,
    created_by      VARCHAR(255),
    version         BIGINT DEFAULT 0,

    CONSTRAINT uk_employees_user_id
        UNIQUE (user_id),

    CONSTRAINT uk_employees_code
        UNIQUE (employee_code),

    CONSTRAINT uk_employees_email
        UNIQUE (email),

    CONSTRAINT fk_employees_department
        FOREIGN KEY (department_id)
        REFERENCES departments (id),

    CONSTRAINT fk_employees_manager
        FOREIGN KEY (manager_id)
        REFERENCES employees (id),

    CONSTRAINT ck_employees_type
        CHECK (employment_type IN ('FULL_TIME', 'CONTRACTOR', 'INTERN')),

    CONSTRAINT ck_employees_status
        CHECK (status IN (
            'ONBOARDING',
            'ACTIVE',
            'ON_LEAVE',
            'NOTICE_PERIOD',
            'EXITED'
        ))
);

CREATE INDEX ix_employees_department_id
    ON employees (department_id);

CREATE INDEX ix_employees_manager_id
    ON employees (manager_id);