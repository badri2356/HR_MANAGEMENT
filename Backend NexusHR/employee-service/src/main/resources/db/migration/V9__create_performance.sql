-- Goals: the half-year is worked out from due_date (Jan–Jun = H1, Jul–Dec = H2), so no period column
CREATE TABLE goals (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT       NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    title       VARCHAR(255) NOT NULL,
    progress    INTEGER      NOT NULL DEFAULT 0,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ON_TRACK',
    due_date    DATE         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(255),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_goals_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_goals_status   CHECK (status IN ('ON_TRACK', 'AT_RISK', 'BEHIND', 'DONE'))
);

-- Speeds up "this employee's goals due between these dates"
CREATE INDEX ix_goals_employee_due ON goals (employee_id, due_date);

-- Reviews: no period, so an employee can be reviewed again later (the scorecard averages all of them)
CREATE TABLE performance_review (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT        NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    reviewer_id BIGINT        NOT NULL REFERENCES employees (id),
    type        VARCHAR(20)   NOT NULL,
    rating      INTEGER       NOT NULL,
    comments    VARCHAR(2000),
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(255),
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_review_type   CHECK (type IN ('SELF', 'MANAGER', 'PEER'))
);

-- Speeds up "all reviews of this employee"
CREATE INDEX ix_review_employee ON performance_review (employee_id);